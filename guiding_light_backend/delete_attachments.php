<?php

require 'db_connect.php';
require 'auth.php';

header('Content-Type: application/json; charset=UTF-8');

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    http_response_code(405);
    echo json_encode(['error' => 'Method not allowed.']);
    exit;
}

$currentUser = requireRole(['admin', 'media']);

$data = json_decode(file_get_contents('php://input'), true);

$id = filter_var(
    is_array($data) ? ($data['id'] ?? null) : null,
    FILTER_VALIDATE_INT
);

if (!$id || $id <= 0) {
    http_response_code(400);
    echo json_encode(['error' => 'A valid attachment ID is required.']);
    exit;
}

try {
    $conn->beginTransaction();

    // Find the parent story. Its row is locked before the final-PDF check.
    $findStmt = $conn->prepare(
        'SELECT post_id FROM story_attachments WHERE id = :id LIMIT 1'
    );
    $findStmt->execute([':id' => $id]);
    $postId = $findStmt->fetchColumn();

    if ($postId === false) {
        $conn->rollBack();
        http_response_code(404);
        echo json_encode(['error' => 'Attachment not found.']);
        exit;
    }

    $parentStmt = $conn->prepare(
        'SELECT content_type
         FROM stories
         WHERE post_id = :post_id
         FOR UPDATE'
    );
    $parentStmt->execute([':post_id' => $postId]);
    $parentStory = $parentStmt->fetch(PDO::FETCH_ASSOC);

    if (!$parentStory) {
        $conn->rollBack();
        http_response_code(404);
        echo json_encode(['error' => 'Parent story not found.']);
        exit;
    }

    // Re-check after locking parent: another request might have deleted it.
    $attachmentStmt = $conn->prepare(
        'SELECT file_path
         FROM story_attachments
         WHERE id = :id AND post_id = :post_id
         FOR UPDATE'
    );
    $attachmentStmt->execute([
        ':id' => $id,
        ':post_id' => $postId
    ]);
    $attachment = $attachmentStmt->fetch(PDO::FETCH_ASSOC);

    if (!$attachment) {
        $conn->rollBack();
        http_response_code(404);
        echo json_encode(['error' => 'Attachment not found.']);
        exit;
    }

    if ($parentStory['content_type'] === 'publication') {
        // Locking/current read (not a stale transaction snapshot) is
        // important if two attachment deletes race on the same publication.
        $countStmt = $conn->prepare(
            'SELECT id FROM story_attachments
             WHERE post_id = :post_id
             FOR UPDATE'
        );
        $countStmt->execute([':post_id' => $postId]);
        $attachmentCount = count($countStmt->fetchAll(PDO::FETCH_COLUMN));

        if ($attachmentCount <= 1) {
            $conn->rollBack();
            http_response_code(409);
            echo json_encode([
                'error' => 'A publication must retain at least one PDF. Upload and save a replacement before deleting the last PDF.'
            ]);
            exit;
        }
    }

    // Commit the DB deletion first. If filesystem cleanup fails afterwards,
    // the only consequence is an orphan file (not a broken database reference).
    $deleteStmt = $conn->prepare(
        'DELETE FROM story_attachments WHERE id = :id'
    );
    $deleteStmt->execute([':id' => $id]);
    $conn->commit();

    // Attachment filenames are server-generated by story_uploads.php.
    $filename = basename($attachment['file_path']);
    $filepath = __DIR__ . '/uploads/stories/attachments/' . $filename;

    if (is_file($filepath) && !@unlink($filepath)) {
        error_log('Failed to remove deleted PDF attachment from storage.');
    }

    echo json_encode(['success' => true]);

} catch (Throwable $e) {
    if ($conn->inTransaction()) {
        $conn->rollBack();
    }

    http_response_code(500);
    echo json_encode(['error' => 'Failed to delete attachment.']);
}
